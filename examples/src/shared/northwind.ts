/**
 * A compact, faithful slice of the classic **Northwind** sample database as
 * portable Postgres DDL + seed data. It is pure SQL text, so the exact same
 * script seeds:
 *   - PGlite (WASM Postgres in the browser) - see demo 338
 *   - a hosted Supabase / Postgres project - see docs/enterprise/studio + the
 *     Supabase sample kit
 *
 * Explicit primary keys (not SERIAL defaults) keep the cross-table foreign
 * keys stable and let the script run idempotently after `DROP ... CASCADE`.
 * `order_lines` is a denormalized VIEW joining order_details -> orders ->
 * customers -> products -> categories: the rich, real-world relational grid a
 * single flat table can't show.
 */

