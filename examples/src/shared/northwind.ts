import type { EntitySchema } from '@svgrid/enterprise'

export type Product = {
  id: number
  name: string
  category_id: number
  unit_price: number
  units_in_stock: number
  discontinued: boolean
}

export type Customer = {
  id: number
  company: string
  contact: string
  city: string
  country: string
}

/** A row of the `order_lines` view - read-only (a five-table join). */
export type OrderLine = {
  id: number
  order_id: number
  order_date: string
  customer: string
  product: string
  category: string
  quantity: number
  unit_price: number
  line_total: number
  ship_country: string
}

export const productsSchema: EntitySchema<Product> = {
  name: 'products',
  label: 'Product',
  idField: 'id',
  fields: [
    { field: 'id', type: 'number', primaryKey: true, readonly: true },
    { field: 'name', type: 'text', label: 'Product', required: true, minLength: 2 },
    { field: 'category_id', type: 'number', label: 'Category #', min: 1, max: 8 },
    { field: 'unit_price', type: 'number', label: 'Unit Price ($)', min: 0 },
    { field: 'units_in_stock', type: 'number', label: 'In Stock', min: 0 },
    { field: 'discontinued', type: 'boolean' },
  ],
}

