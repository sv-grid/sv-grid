#!/usr/bin/env node
/**
 * Put "SvGrid Studio, a tour" on the Studio docs page: a web copy of the
 * render (960 x 540), its poster and captions under website/public/tutorials/,
 * and the manifest entry tools/tutorials/embed.mjs places on
 * docs/enterprise/studio.md, above the screenshot under the intro. The
 * captions are the SRT the render wrote, so they match the voice.
 *
 *   node tools/promo/studio-tour/docs-media.mjs
 *   node tools/tutorials/embed.mjs
 */
import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { toVtt } from '../../lib/tutorial-media.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..', '..', '..')
const SRC = join(ROOT, 'marketing', 'videos', 'studio-tour')
const PUB = join(ROOT, 'website', 'public', 'tutorials')
const ID = 'mk-studio-tour'

const r2 = (x) => Math.round(x * 100) / 100
const secs = (ts) => { const [h, m, s] = ts.replace(',', '.').split(':').map(Number); return h * 3600 + m * 60 + s }
const transcript = readFileSync(join(SRC, 'studio-tour.srt'), 'utf8').trim().split(/\r?\n\r?\n/).map((cue) => {
  const [, time, ...text] = cue.split(/\r?\n/)
  const [a, b] = time.split(' --> ')
  return { start: r2(secs(a)), end: r2(secs(b)), text: text.join(' ').trim() }
})
const duration = r2(Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', join(SRC, 'studio-tour.mp4')], { encoding: 'utf8' })))

const mp4 = join(PUB, `${ID}.mp4`)
const poster = join(PUB, `${ID}.poster.webp`)
execFileSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', '-i', join(SRC, 'studio-tour.mp4'), '-vf', 'scale=960:540', '-c:v', 'libx264', '-preset', 'slow', '-crf', '30',
  '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '96k', '-movflags', '+faststart', mp4])
execFileSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', '-i', join(SRC, 'poster.jpg'), '-vf', 'scale=960:540', '-quality', '78', poster])
writeFileSync(join(PUB, `${ID}.vtt`), toVtt(transcript))

const manifestPath = join(ROOT, 'tools', 'tutorials', 'manifest.json')
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
const entry = {
  id: ID,
  kind: 'marketing',
  player: true,
  title: 'SvGrid Studio: from your database to a SvelteKit app',
  description: 'A narrated tour of SvGrid Studio: the data model, screens, themes, logic, preview, and the SvelteKit app it generates and deploys.',
  demo: null,
  docsPage: 'docs/enterprise/studio.md',
  anchor: '![A CRUD screen generated by SvGrid Studio',
  tags: ['svgrid studio', 'sveltekit app builder', 'svelte crud generator', 'admin panel', 'internal tools', 'low code'],
  duration,
  width: 960,
  height: 540,
  recordedAt: new Date().toISOString().slice(0, 10),
  files: { mp4: `/tutorials/${ID}.mp4`, poster: `/tutorials/${ID}.poster.webp`, vtt: `/tutorials/${ID}.vtt` },
  bytes: { mp4: statSync(mp4).size, poster: statSync(poster).size, master: statSync(join(SRC, 'studio-tour.mp4')).size },
  transcript,
}
const list = manifest.tutorials
const i = list.findIndex((t) => t.id === ID)
if (i >= 0) list[i] = entry
else list.push(entry)
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n')
console.log(`${ID}: ${(entry.bytes.mp4 / 1048576).toFixed(2)} MB mp4, ${Math.round(entry.bytes.poster / 1024)} KB poster, ${transcript.length} cues, ${entry.duration}s`)
