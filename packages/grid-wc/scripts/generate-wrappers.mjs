/**
 * Generate the React, Vue and Angular wrappers from the same surface the
 * custom elements are generated from.
 *
 * Why generated rather than hand-written: three wrappers x 98 props x 19 events
 * is 350-odd declarations that must agree with the element, with each other and
 * with the docs. Hand-kept, they would drift the week after they landed - which
 * is exactly how `<sv-grid>` ended up exposing 7 of 100 props while the docs
 * said otherwise. One source, four consumers (two elements, three wrappers),
 * one `--check` gate.
 *
 * What each wrapper is actually for:
 *
 *   React   - React <=18 stringifies object props onto ATTRIBUTES, so
 *             `columns={cols}` silently becomes "[object Object]" and the grid
 *             renders empty. The wrapper assigns them as properties.
 *   Vue     - removes the `isCustomElement` build config and the `.prop`
 *             modifier a raw element needs.
 *   Angular - removes `CUSTOM_ELEMENTS_SCHEMA` and gives typed @Input/@Output.
 *
 * Usage:
 *   node scripts/generate-wrappers.mjs           write the wrapper sources
 *   node scripts/generate-wrappers.mjs --check   fail if they are stale (CI)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { ELEMENT_PROPS, ELEMENT_EVENTS, LEGACY_EVENTS } from '../src/surface.generated.js'

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, '..', 'src')

const BANNER = (script) => `/**
 * AUTO-GENERATED by scripts/generate-wrappers.mjs - DO NOT EDIT.
 * Regenerate: pnpm --filter @svgrid/grid-wc generate:wrappers
 *
 * ${script}
 */`

/**
 * A prop's TypeScript type, made safe to paste into a wrapper.
 *
 * `<SvGrid>`'s types are generic over the feature set and the row type, and
 * carry inline object literals hundreds of characters long. Neither survives
 * being lifted out of context, so anything generic or structural degrades to
 * `unknown` and the reader is pointed at the grid's own types. The primitives -
 * which is most of the surface - keep their real type, and those are the ones
 * a consumer actually gets wrong.
 */
function tsType(p) {
  const t = p.ts.replace(/\s+/g, ' ').trim()
  if (/^boolean$/.test(t)) return 'boolean'
  if (/^number$/.test(t)) return 'number'
  if (/^string$/.test(t)) return 'string'
  if (/^string \| null$/.test(t)) return 'string | null'
  // A union of string literals is safe and genuinely useful - it is what makes
  // `filterMode` autocomplete to "row" | "menu" | "global" | "none".
  if (/^(['"][^'"]*['"]\s*\|\s*)*['"][^'"]*['"]$/.test(t)) return t.replace(/'/g, '"')
  if (p.type === 'Array') return 'readonly unknown[]'
  if (p.type === 'Number') return 'number'
  if (p.type === 'String') return 'string'
  if (p.type === 'Boolean') return 'boolean'
  return 'unknown'
}

/** React/Vue/Angular handler name for an event: `cellvaluechange` -> `onCellValueChange`. */
const handlerName = (e) => e.callback

/** Events a wrapper exposes: the generated set plus the legacy aliases. */
const ALL_EVENTS = [
  ...ELEMENT_EVENTS.map((e) => ({ ...e, legacy: false })),
  ...LEGACY_EVENTS.filter((l) => !ELEMENT_EVENTS.some((e) => e.event === l.event)).map((l) => ({
    callback: `on${l.event[0].toUpperCase()}${l.event.slice(1)}`,
    event: l.event,
    params: [l.pick],
    detail: 'unknown',
    legacy: true,
    note: l.note,
  })),
]

const propNames = ELEMENT_PROPS.map((p) => p.name)
const eventNames = ALL_EVENTS.map((e) => e.event)

// ---------------------------------------------------------------------------
// React
// ---------------------------------------------------------------------------

function react() {
  const props = ELEMENT_PROPS.map(
    (p) => `  /** \`${p.attribute ?? 'property only'}\` - ${p.ts.replace(/\s+/g, ' ').slice(0, 90)} */\n  ${p.name}?: ${tsType(p)}`,
  ).join('\n')

  const handlers = ALL_EVENTS.map(
    (e) =>
      `  /** \`${e.event}\`${e.legacy ? ` - ${e.note}` : ''} */\n  ${handlerName(e)}?: (detail: ${e.detail ?? 'unknown'}) => void`,
  ).join('\n')

  return `${BANNER('React wrapper. React <=18 assigns object props to ATTRIBUTES, which turns `columns` into "[object Object]"; this assigns them as properties instead.')}
import { createElement, forwardRef, useEffect, useImperativeHandle, useRef } from 'react'
import type { Ref } from 'react'
import '@svgrid/grid-wc'

export interface SvGridProps {
${props}

${handlers}

  /** Render inside an open shadow root, so page CSS cannot reach the grid. */
  shadow?: boolean
  /** Forwarded to the host element. */
  className?: string
  style?: Record<string, string | number>
}

/** The grid's imperative api, reachable through a ref. */
export interface SvGridHandle {
  /** The host custom element. */
  element: HTMLElement | null
  /** The grid api, once \`apiready\` has fired. */
  api: unknown
}

const PROP_NAMES = ${JSON.stringify(propNames)} as const

const EVENTS: Array<[handler: string, event: string]> = ${JSON.stringify(
    ALL_EVENTS.map((e) => [handlerName(e), e.event]),
  )}

/**
 * SvGrid as a React component.
 *
 * Every non-primitive prop is assigned as a DOM property in an effect rather
 * than passed through JSX, because React 18 and earlier stringify them onto
 * attributes and an attribute cannot hold an array.
 */
export const SvGrid = forwardRef(function SvGrid(props: SvGridProps, ref: Ref<SvGridHandle>) {
  const hostRef = useRef<HTMLElement | null>(null)
  const { shadow, className, style, ...rest } = props

  // The shadow element is a separate bundle; only pay for it when asked.
  useEffect(() => {
    if (shadow) void import('@svgrid/grid-wc/shadow')
  }, [shadow])

  // Assign only what CHANGED. This effect has no dependency array - 98 props
  // cannot be listed, and listing a subset would silently miss the rest - so it
  // runs on every render, and writing all 98 each time would hand the grid 98
  // fresh values per keystroke of parent state. Comparing first also stops the
  // wrapper clobbering a value the grid maintains itself.
  const written = useRef<Record<string, unknown>>({})
  useEffect(() => {
    const el = hostRef.current as (HTMLElement & Record<string, unknown>) | null
    if (!el) return
    for (const name of PROP_NAMES) {
      const value = (rest as Record<string, unknown>)[name]
      if (value === undefined || Object.is(written.current[name], value)) continue
      written.current[name] = value
      el[name] = value
    }
  })

  // Handlers go through a ref so the listeners can be bound ONCE. Binding them
  // per render - which is what an effect with no deps does - would add and
  // remove 20 listeners on every parent state change, and inline arrow handlers
  // (the normal way to write them) change identity every render, so a deps
  // array on the handlers themselves would not help either.
  const handlers = useRef(rest as Record<string, unknown>)
  handlers.current = rest as Record<string, unknown>

  useEffect(() => {
    const el = hostRef.current
    if (!el) return
    const bound: Array<[string, EventListener]> = []
    for (const [handler, event] of EVENTS) {
      const listener: EventListener = (e) => {
        const fn = handlers.current[handler] as ((detail: unknown) => void) | undefined
        fn?.((e as CustomEvent).detail)
      }
      el.addEventListener(event, listener)
      bound.push([event, listener])
    }

    // \`apiready\` fires ONCE, during the element's own mount - which is before
    // React can bind anything, so the handler would simply never run. The
    // element parks the handle on itself for exactly this reason, so replay it.
    // (Vue happens to bind early enough to win that race; relying on the order
    // would be luck, so all three wrappers replay.)
    const onReady = handlers.current.onApiReady as ((detail: unknown) => void) | undefined
    const api = (el as HTMLElement & { api?: unknown }).api
    if (onReady && api != null) onReady(api)

    return () => {
      for (const [event, listener] of bound) el.removeEventListener(event, listener)
    }
  }, [])

  useImperativeHandle(
    ref,
    () => ({
      get element() {
        return hostRef.current
      },
      get api() {
        return (hostRef.current as (HTMLElement & { api?: unknown }) | null)?.api ?? null
      },
    }),
    [],
  )

  return createElement(shadow ? 'sv-grid-shadow' : 'sv-grid', {
    ref: hostRef,
    class: className,
    style: { display: 'block', height: '100%', ...style },
  })
})

export default SvGrid
`
}

// ---------------------------------------------------------------------------
// Vue
// ---------------------------------------------------------------------------

function vue() {
  return `${BANNER('Vue wrapper. Removes the `isCustomElement` build config and the `.prop` modifier a raw custom element needs.')}
import { defineComponent, h, onMounted, ref, watchEffect } from 'vue'
import type { PropType } from 'vue'
import '@svgrid/grid-wc'

const PROP_NAMES = ${JSON.stringify(propNames)} as const
const EVENT_NAMES = ${JSON.stringify(eventNames)} as const

export type SvGridProps = {
${ELEMENT_PROPS.map((p) => `  ${p.name}?: ${tsType(p)}`).join('\n')}
  shadow?: boolean
}

/**
 * SvGrid as a Vue component.
 *
 * Props are declared loosely (\`null\` type) and forwarded as DOM PROPERTIES
 * through the \`.\`-prefixed vnode key, which is Vue's own way of forcing a
 * property assignment - the same thing \`:columns.prop\` does in a template,
 * applied to all ${propNames.length} of them so a consumer never has to think about it.
 */
export const SvGrid = defineComponent({
  name: 'SvGrid',
  props: {
    ...Object.fromEntries(PROP_NAMES.map((n) => [n, { type: null as unknown as PropType<unknown>, required: false }])),
    shadow: { type: Boolean, default: false },
  },
  emits: [...EVENT_NAMES],
  setup(props, { emit, expose }) {
    const host = ref<HTMLElement | null>(null)

    watchEffect(() => {
      if (props.shadow) void import('@svgrid/grid-wc/shadow')
    })

    onMounted(() => {
      const el = host.value
      if (!el) return
      for (const name of EVENT_NAMES)
        el.addEventListener(name, (e) => emit(name, (e as CustomEvent).detail))

      // \`apiready\` fires once, during the element's own mount, so a listener
      // bound here can miss it. The element parks the handle for that reason.
      const api = (el as HTMLElement & { api?: unknown }).api
      if (api != null) emit('apiready', api)
    })

    expose({
      get element() {
        return host.value
      },
      get api() {
        return (host.value as (HTMLElement & { api?: unknown }) | null)?.api ?? null
      },
    })

    return () => {
      const attrs: Record<string, unknown> = { ref: host, style: { display: 'block', height: '100%' } }
      for (const name of PROP_NAMES) {
        const value = (props as Record<string, unknown>)[name]
        // A leading '.' forces a DOM property assignment in Vue's runtime-dom,
        // which is what arrays and objects need.
        if (value !== undefined) attrs['.' + name] = value
      }
      return h(props.shadow ? 'sv-grid-shadow' : 'sv-grid', attrs)
    }
  },
})

export default SvGrid
`
}

