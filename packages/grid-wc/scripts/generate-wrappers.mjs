/**
 * The package shipped NO types at all, so `import '@svgrid/grid-wc'` was an
 * error under `moduleResolution: bundler`, and `document.querySelector('sv-grid')`
 * came back as a bare `Element`. The TypeScript docs page told readers to
 * hand-write these declarations; shipping them is strictly better, and the
 * Angular wrapper cannot compile without them.
 */
function elementTypes() {
  const props = ELEMENT_PROPS.map(
    (p) =>
      `  /** ${p.attribute ? `attribute \`${p.attribute}\`` : 'property only - an attribute cannot hold this'} */\n  ${p.name}: ${tsType(p)}`,
  ).join('\n')

  const events = ALL_EVENTS.map(
    (e) => `    ${e.event}: CustomEvent<unknown>`,
  ).join('\n')

  return `${BANNER('Type declarations for the custom elements.')}

/**
 * The custom element's own surface. Complex props (columns, data, configs)
 * are \`unknown\` here rather than wrong: their real types are generic over
 * the feature set and the row type, which cannot be reproduced outside
 * \`@svgrid/grid\`. Import them from there when you want them checked.
 */
export interface SvGridElement extends HTMLElement {
${props}

  /** The grid api. Present once \`apiready\` has fired. */
  readonly api: unknown
}

declare global {
  interface HTMLElementTagNameMap {
    'sv-grid': SvGridElement
    'sv-grid-shadow': SvGridElement
  }

  interface HTMLElementEventMap {
${events}
  }
}

export {}
`
}

const FILES = [
  ['types/elements.d.ts', elementTypes()],
  ['react/index.tsx', react()],
  ['vue/index.ts', vue()],
  ['angular/svgrid.component.ts', angular()],
  [
    'angular/public-api.ts',
    `${BANNER('Angular entry point.')}
export { SvGridComponent } from './svgrid.component'
`,
  ],
]

const check = process.argv.includes('--check')
const stale = []

for (const [rel, content] of FILES) {
  const path = join(src, rel)
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : ''
    if (current.replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) stale.push(rel)
    continue
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
}

if (check) {
  if (stale.length) {
    console.error(
      `generate-wrappers: STALE: ${stale.join(', ')}. ` +
        `Run: pnpm --filter @svgrid/grid-wc generate:wrappers`,
    )
    process.exit(1)
  }
  console.log('generate-wrappers: wrapper sources are current')
} else {
  console.log(
    `generate-wrappers: react + vue + angular, ${propNames.length} props / ${ALL_EVENTS.length} events each`,
  )
}
